"""Regenerate public VICAL interoperability fixtures (cryptography and cbor2).

Keys exist only in memory and are never written. Output contains public certificates
and signed empty VICALs. Fixed validation time in tests: 2026-10-22T00:00:00Z.
"""
import base64
import sys
from datetime import datetime, timezone
from pathlib import Path

import cbor2
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature
from cryptography.x509.oid import NameOID, ObjectIdentifier

start = datetime(2026, 1, 1, tzinfo=timezone.utc)
root_key = ec.generate_private_key(ec.SECP256R1())
root_name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, 'VICAL fixture CA')])
root = (x509.CertificateBuilder().subject_name(root_name).issuer_name(root_name)
        .public_key(root_key.public_key()).serial_number(x509.random_serial_number())
        .not_valid_before(start).not_valid_after(datetime(2035, 1, 1, tzinfo=timezone.utc))
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), True)
        .add_extension(x509.KeyUsage(False, False, False, False, False, True, True, False, False), True)
        .add_extension(x509.SubjectKeyIdentifier.from_public_key(root_key.public_key()), False)
        .sign(root_key, hashes.SHA256()))

def signed_vical(case):
    key = ec.generate_private_key(ec.SECP256R1())
    subject = [x509.NameAttribute(NameOID.COUNTRY_NAME, 'NL'),
               x509.NameAttribute(NameOID.COMMON_NAME, 'VICAL fixture')]
    if case != 'missingOrganization':
        subject.append(x509.NameAttribute(NameOID.ORGANIZATION_NAME, 'VICAL fixture provider'))
    end = datetime(2031 if case == 'longValidity' else 2028, 1, 1, tzinfo=timezone.utc)
    builder = (x509.CertificateBuilder().subject_name(x509.Name(subject)).issuer_name(root_name)
               .public_key(key.public_key()).serial_number(1 if case == 'shortSerial' else x509.random_serial_number())
               .not_valid_before(start).not_valid_after(end))
    if case != 'missingKeyUsage':
        builder = builder.add_extension(x509.KeyUsage(case == 'wrongKeyUsage', case != 'wrongKeyUsage', False, False, False, False, False, False, False), True)
    if case != 'missingEku':
        builder = builder.add_extension(x509.ExtendedKeyUsage([ObjectIdentifier('1.0.18013.5.1.2' if case == 'wrongEku' else '1.0.18013.5.1.8')]), True)
    builder = builder.add_extension(x509.SubjectKeyIdentifier.from_public_key(key.public_key()), False)
    if case != 'missingAki':
        builder = builder.add_extension(x509.AuthorityKeyIdentifier.from_issuer_public_key(root_key.public_key()), False)
    if case != 'missingCrl':
        builder = builder.add_extension(x509.CRLDistributionPoints([
            x509.DistributionPoint(full_name=[x509.UniformResourceIdentifier('https://vical.example.test/ca.crl')], relative_name=None, reasons=None, crl_issuer=None)
        ]), False)
    cert = builder.sign(root_key, hashes.SHA256()).public_bytes(serialization.Encoding.DER)
    payload = cbor2.dumps({'version': '1.0', 'vicalProvider': 'Fixture provider', 'vicalIssueID': 0,
                           'date': cbor2.CBORTag(0, '2026-10-21T00:00:00Z'),
                           'nextUpdate': cbor2.CBORTag(0, '2026-10-23T00:00:00Z'), 'certificateInfos': []})
    protected = cbor2.dumps({1: -7})
    to_sign = cbor2.dumps(['Signature1', protected, b'', payload])
    r, s = decode_dss_signature(key.sign(to_sign, ec.ECDSA(hashes.SHA256())))
    return cbor2.dumps([protected, {33: [cert]}, payload, r.to_bytes(32, 'big') + s.to_bytes(32, 'big')])

cases = ['valid', 'wrongKeyUsage', 'missingKeyUsage', 'wrongEku', 'missingEku', 'longValidity', 'missingAki', 'missingCrl', 'missingOrganization', 'shortSerial']
lines = ['/* Public test fixtures; generated by commonTest/fixtures/generate_vical_signer_fixtures.py. */',
         'package com.sphereon.mdoc.vical', '', 'internal object VicalSignerFixtures {',
         '    const val root = "' + base64.b64encode(root.public_bytes(serialization.Encoding.DER)).decode() + '"']
for case in cases:
    lines.append('    const val ' + case + ' = "' + base64.b64encode(signed_vical(case)).decode() + '"')
lines.append('}')
Path(sys.argv[1]).write_text('\n'.join(lines) + '\n', encoding='utf-8')
